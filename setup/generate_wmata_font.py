def generate_bdf(filepath):
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, 'w') as f:
        f.write("STARTFONT 2.1\n")
        f.write("FONT -WMATA-PIDS-Medium-R-Normal--7-70-75-75-C-60-ISO10646-1\n")
        f.write("SIZE 7 75 75\n")
        f.write("FONTBOUNDINGBOX 6 7 0 0\n")
        f.write("STARTPROPERTIES 10\n")
        f.write("FONT_ASCENT 7\n")
        f.write("FONT_DESCENT 0\n")
        f.write("CAP_HEIGHT 7\n")
        f.write("X_HEIGHT 5\n")
        f.write("ENDPROPERTIES\n")
        f.write(f"CHARS {len(font_data)}\n")
        
        for char, bitmap in font_data.items():
            f.write(f"STARTCHAR {char}\n")
            f.write(f"ENCODING {ord(char)}\n")
            f.write("SWIDTH 600 0\n")
            f.write("DWIDTH 6 0\n")
            f.write("BBX 5 7 0 0\n")
            f.write("BITMAP\n")
            for row in bitmap:
                # convert '.###.' to '01110' -> append '000' for byte padding -> '01110000'
                bits = row.replace('.', '0').replace('#', '1') + '000'
                hex_val = hex(int(bits, 2))[2:].zfill(2).upper()
                f.write(f"{hex_val}\n")
            f.write("ENDCHAR\n")
        f.write("ENDFONT\n")

if __name__ == "__main__":
    out_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), "src", "fonts", "wmata_5x7.bdf")
    generate_bdf(out_path)
    print(f"WMATA font generated successfully at {out_path}!")
